/*
 * Shared build export helpers. The builder toolbar itself now lives in BuilderPage (ported from the
 * design mock); these functions are reused by My Builds, the summary page and the builder.
 */
import type { BuildSnapshot, CatalogItem } from '../../contracts';
import { KIND_LABELS, TIERS, TIER_LABELS, kindsInTier } from '../../contracts';

/** Triggers a client-side file download (no server round trip). */
export function download(name: string, text: string, type = 'application/json') {
  const url = URL.createObjectURL(new Blob([text], { type }));
  const a = document.createElement('a');
  a.href = url;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/** Keep user and catalog text literal and confined to one Markdown line or table cell. */
function markdownText(value: string): string {
  return value
    .replace(/\r\n|[\r\n\u2028\u2029]/g, ' ')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/[\\`*_{}[\]|#~]/g, '\\$&')
    .replace(/:\/\//g, '\\://')
    .replace(/\bwww\./gi, (match) => `${match.slice(0, -1)}\\.`)
    .replace(/@/g, '\\@');
}

/** Human-readable Markdown summary of a build (kept alongside the JSON export). */
export function buildMarkdown(
  build: BuildSnapshot,
  byId: ReadonlyMap<string, CatalogItem>,
  dataMode: 'fixture' | 'http',
): string {
  const lines = [
    `# ${markdownText(build.name)}`,
    '',
    `Revision ${build.revision} · contract BuildSnapshot ${markdownText(build.schema_version)} · catalog ${markdownText(build.locks.catalog_snapshot_id)}`,
    '',
  ];
  for (const tier of TIERS) {
    const rows = kindsInTier(tier).flatMap((k) =>
      build.selections.filter((s) => s.kind === k.kind),
    );
    if (!rows.length) continue;
    lines.push(
      `## ${tier} — ${TIER_LABELS[tier]}`,
      '',
      '| Component | Selection | Role | Enabled |',
      '|---|---|---|---|',
    );
    for (const s of rows) {
      const candidate = byId.get(s.catalog_item_id);
      const item = candidate?.kind === s.kind ? candidate : undefined;
      let name = !item
        ? `${s.catalog_item_id} (not in current catalog; selected version: ${s.catalog_item_version})`
        : item.version !== s.catalog_item_version
          ? `${item.name} (current catalog name; selected version: ${s.catalog_item_version}; current catalog version: ${item.version})`
          : item.name;
      if (item?.tags?.includes('synthetic')) {
        name +=
          item.version === s.catalog_item_version
            ? ' (synthetic)'
            : ' (current catalog record is synthetic)';
      }
      lines.push(
        `| ${markdownText(KIND_LABELS[s.kind])} | ${markdownText(name)} | ${markdownText(s.role)} | ${s.enabled ? 'yes' : 'no'} |`,
      );
    }
    lines.push('');
  }
  lines.push(
    dataMode === 'fixture'
      ? '_Generated by PickYour.AI preview. Demo components, prices and results are synthetic._'
      : '_Generated by PickYour.AI._',
    '',
  );
  return lines.join('\n');
}
